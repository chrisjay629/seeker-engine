"""Benchmark: Seeker vs Perplexity on the same hard investigative question (task #21).

THE POINT is to find out whether Seeker earns its runtime. Chris's north star is that Seeker must
return MORE valuable, connected information than other platforms for the same question — and that
has never once been measured. Every quality signal in this project so far was generated by Seeker
itself, so a pass told us nothing about the world.

DESIGNED TO BE ABLE TO EMBARRASS SEEKER, on purpose:
  • Perplexity gets its BEST model (sonar-deep-research, their multi-step research agent), not the
    cheap one. sonar-pro runs too, as the "what you'd get in thirty seconds" baseline.
  • Both conditions are run. WITH-ROSTER is the fair comparison, because Seeker was handed the
    thirteen names as seeds; NO-ROSTER is the harder test Seeker was never asked to do, reported
    separately rather than blended in to flatter anyone.
  • Scoring is DETERMINISTIC and fixed before the results were seen. No model judges the winner —
    a judge would be one more self-generated signal, which is the exact hole this exists to close.

WHAT IS COUNTED, per system: how many of the thirteen people are named at all; how many get a
STATUS; how many get a DOCUMENTED CAUSE; how many carry a date or place; whether the coordination
claim is called unproven; and how many sources are cited. Coverage is the metric that matters —
a system that answers about four of thirteen people has not answered the question asked.
"""
import json
import os
import re
import sys
import time

sys.path.insert(0, "src")
from dotenv import load_dotenv
load_dotenv()
import requests

Q = ("The 2026 'missing scientists' case: for EACH named individual, verified status and documented "
     "cause — and is there a genuine coordinated pattern or a coincidental cluster of unrelated cases?")
ROSTER = ["William Neil McCasland", "Monica Jacinto Reza", "Anthony Chavez", "Steven Garcia",
          "Carl Grillmair", "Nuno Loureiro", "Jason Thomas", "Melissa Casias", "Frank Maiwald",
          "Michael David Hicks", "Matthew James Sullivan", "Amy Eskridge", "Joshua LeBlanc"]

_STATUS = re.compile(r"\b(missing|deceased|died|dead|killed|found dead|alive|disappeared)\b", re.I)
_CAUSE = re.compile(r"\b(homicide|suicide|gunshot|cardiovascular|heart|accident|overdose|"
                    r"undetermined|natural causes|drowning|fire|crash|shot)\b", re.I)
_WHEN = re.compile(r"\b(19|20)\d{2}\b|\b(January|February|March|April|May|June|July|August|"
                   r"September|October|November|December)\b", re.I)
_UNPROVEN = re.compile(r"\b(unproven|not (been )?(confirmed|established|verified|substantiated)|"
                       r"no (official |verified )?evidence|speculation|unverified|coincidence|"
                       r"unrelated)\b", re.I)


def score(text: str, cites: int, label: str) -> dict:
    """Per-person coverage, counted the same way for every system."""
    named = status = cause = dated = 0
    for name in ROSTER:
        surname = name.split()[-1]
        hits = [m.start() for m in re.finditer(re.escape(surname), text, re.I)]
        if not hits:
            continue
        named += 1
        # the person's neighbourhood: 400 chars around any mention, unioned
        seg = " ".join(text[max(0, h - 120): h + 400] for h in hits[:3])
        if _STATUS.search(seg):
            status += 1
        if _CAUSE.search(seg):
            cause += 1
        if _WHEN.search(seg):
            dated += 1
    return {"system": label, "named": named, "status": status, "cause": cause,
            "dated": dated, "calls_unproven": bool(_UNPROVEN.search(text)),
            "citations": cites, "chars": len(text)}


def ask_perplexity(model: str, question: str) -> tuple:
    """Returns (text, citation_count, elapsed_seconds). Time is recorded because a quality score
    without it is a dishonest comparison: Seeker spent 1h29m and real credits gathering 500
    findings, Perplexity gets one call. If Seeker only ties, it has LOST — it cost far more to
    reach the same place (Noor's objection, and the right one)."""
    t0 = time.time()
    r = requests.post("https://api.perplexity.ai/chat/completions",
                      headers={"Authorization": f"Bearer {os.environ['PERPLEXITY_API_KEY']}",
                               "Content-Type": "application/json"},
                      json={"model": model, "messages": [{"role": "user", "content": question}]},
                      timeout=900)
    r.raise_for_status()
    d = r.json()
    text = d["choices"][0]["message"]["content"]
    cites = len(d.get("search_results") or d.get("citations") or [])
    return text, cites, round(time.time() - t0, 1)


if __name__ == "__main__":
    rows, raw = [], {}

    seeker_text = open("runs/v20_report.md").read()
    srow = score(seeker_text, 0, "Seeker v20")
    srow["seconds"] = 5340   # 1h29m of searching; the write-up pass is on top of that
    rows.append(srow)
    print(json.dumps(rows[-1]), flush=True)

    with_roster = Q + "\n\nThe individuals are: " + ", ".join(ROSTER) + "."
    for model, cond, q in [("sonar-pro", "with-roster", with_roster),
                           ("sonar-deep-research", "with-roster", with_roster),
                           ("sonar-deep-research", "no-roster", Q)]:
        label = f"Perplexity {model} ({cond})"
        try:
            text, cites, secs = ask_perplexity(model, q)
            raw[label] = text
            row = score(text, cites, label); row["seconds"] = secs
            rows.append(row)
        except Exception as e:
            rows.append({"system": label, "error": repr(e)[:160]})
        print(json.dumps(rows[-1]), flush=True)

    json.dump({"rows": rows, "raw": raw}, open("runs/benchmark_perplexity.json", "w"),
              indent=2, default=str)
    print(">>> BENCHMARK DONE", flush=True)
